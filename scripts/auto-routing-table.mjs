// Generates docs/AUTO_ROUTING.md from the routing policies in
// lib/routing/policy.ts (Node 22.6+ runs the TypeScript module directly).
//
//   npm run docs:auto-routing
import { writeFileSync } from "node:fs";
import { choosePolicy, DIFFICULTIES, TASKS } from "../lib/routing/policy.ts";

// Keep in sync with expensiveModels in lib/utils/model-provider.ts
const PREMIUM = ["gpt6astra", "gpt61sol", "gptLatest", "claudefable51", "claudeopus55"];

const NAMES = {
    gpt6luna: "GPT-6 Luna",
    gpt61terra: "GPT-6.1 Terra",
    gpt61sol: "GPT-6.1 Sol",
    gpt6astra: "GPT-6 Astra",
    claudesonnet55: "Claude Sonnet 5.5"
};
const LEVELS = { low: "low", medium: "medium", high: "high", xhigh: "extra high" };

const format = ({ model, reasoning }) => `${NAMES[model] ?? model}, ${LEVELS[reasoning]}`;

const route = (priority, difficulty, task, { deep = false, premium = true, repo = false } = {}) =>
    format(
        choosePolicy(priority, {
            task,
            difficulty,
            needsDeepThinking: deep,
            repoConnected: repo,
            isAvailable: (model) => premium || !PREMIUM.includes(model)
        })
    );

const same = (value, base) => (value === base ? "same" : `**${value}**`);

const fullTable = (priority) => {
    const rows = [
        "| Difficulty | Task | Default | Needs deep thinking | Premium models off | Premium off + deep thinking | Repo connected |",
        "|---|---|---|---|---|---|---|"
    ];
    for (const difficulty of DIFFICULTIES) {
        for (const task of TASKS) {
            const base = route(priority, difficulty, task);
            rows.push(
                `| ${difficulty} | ${task} | ${base} | ${route(priority, difficulty, task, { deep: true })} | ${same(route(priority, difficulty, task, { premium: false }), base)} | ${route(priority, difficulty, task, { premium: false, deep: true })} | ${same(route(priority, difficulty, task, { repo: true }), base)} |`
            );
        }
    }
    return rows.join("\n");
};

const comparison = () => {
    const rows = ["| Difficulty | Task | Cost (default) | Performance (first version) |", "|---|---|---|---|"];
    for (const difficulty of DIFFICULTIES) {
        for (const task of TASKS) {
            const cost = route("cost", difficulty, task);
            const performance = route("performance", difficulty, task);
            rows.push(`| ${difficulty} | ${task} | ${cost} | ${cost === performance ? "same" : performance} |`);
        }
    }
    return rows.join("\n");
};

const doc = `# Auto routing

<!-- Generated by \`npm run docs:auto-routing\` from lib/routing/policy.ts. Don't edit by hand. -->

Auto picks a model and reasoning effort for every message (\`lib/routing/auto-router.ts\`):

1. **Fast path**: obviously trivial messages ("hi", "thanks") skip classification: GPT-6 Luna, low.
2. **Classifier** (Settings → Auto Router, default GPT-OSS 20B on Groq): labels the latest message with a **task** (${TASKS.join(", ")}), a **difficulty** (${DIFFICULTIES.join(", ")}) and whether it **needs deep thinking**. If it fails or takes over 3.5 s, keyword heuristics decide instead.
3. **Rules**: a request that contains or mentions code is a coding task, whatever the classifier said.
4. **Policy** (Settings → Auto Priority, default **Cost**): maps the labels to a model and effort, shown below. "Needs deep thinking" raises the effort one level on the same model. Premium models (GPT-6 Astra, GPT-6.1 Sol, Claude Fable 5.1, Claude Opus 5.5) are only available when \`NEXT_PUBLIC_ENABLE_EXPENSIVE_MODELS=true\`; otherwise the policy falls back to the next model in line.

The chosen model and reason are shown in the message's model badge.

## Cost vs Performance

Default columns (premium models on, no deep thinking, no repository connected).

${comparison()}

**Cost** (the default since 2026-11-01): Luna handles everything up to standard difficulty, and more reasoning effort on a cheaper model is tried before a pricier model. Terra only takes complex work, Sol only expert work; Astra and Claude are never picked.

**Performance** (the first version of the new router): stronger models earlier. Terra for standard coding, writing and creative work, Sol for complex technical work, Claude Sonnet 5.5 for complex writing, Astra for expert work, and coding with a connected GitHub repository never on Luna.

## Cost (default): every combination

${fullTable("cost")}

## Performance: every combination

${fullTable("performance")}

"same" means the result doesn't change from the Default column; bold means it does.
`;

writeFileSync(new URL("../docs/AUTO_ROUTING.md", import.meta.url), doc);
console.log("Wrote docs/AUTO_ROUTING.md");
